#[test]
fn write_profile_contains_skeleton_and_all_sections() {
    let dir = tmp_dir("skeleton");
    let meta = ProfileMeta {
        generated_at: "2026-07-03T00:00:00+00:00".to_string(),
        last_distilled_ts: "2026-07-01T00:00:00+00:00".to_string(),
        session_count: 5,
        sources: vec!["claude_code".to_string()],
        facts_count: 3,
    };
    let path = write_profile(&dir, ProfileScope::Work, &sample_sections(), &meta).unwrap();
    let content = fs::read_to_string(&path).unwrap();
    assert!(content.starts_with(&format!(
        "# User Profile — generated by HalluScribe {HALLUSCRIBE_VERSION} on 2026-07-03 from 5 sessions"
    )));
    for section in ProfileScope::Work.sections() {
        let section = *section;
        assert!(content.contains(&format!("## {}", section.heading())));
    }
    assert!(content.contains("Rust/Tauri developer."));
    assert!(content.contains("_No facts distilled yet._"));
}

#[test]
fn write_profile_writes_meta_roundtrip() {
    let dir = tmp_dir("meta_roundtrip");
    let meta = ProfileMeta {
        generated_at: "2026-07-03T00:00:00+00:00".to_string(),
        last_distilled_ts: "2026-07-01T00:00:00+00:00".to_string(),
        session_count: 5,
        sources: vec!["claude_code".to_string(), "codex".to_string()],
        facts_count: 3,
    };
    write_profile(&dir, ProfileScope::Work, &sample_sections(), &meta).unwrap();
    let loaded = load_meta(&dir, ProfileScope::Work);
    assert_eq!(loaded.session_count, 5);
    assert_eq!(loaded.facts_count, 3);
    assert_eq!(loaded.sources, meta.sources);
    assert_eq!(loaded.last_distilled_ts, "2026-07-01T00:00:00+00:00");
}

