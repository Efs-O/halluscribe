#[test]
fn digest_filename_uses_iso_week() {
    let dir = tmp_dir("digest_filename");
    // 2026-07-06 is a Monday; ISO week 28 of 2026.
    let now = Utc.with_ymd_and_hms(2026, 7, 6, 12, 0, 0).unwrap();
    let entries = [entry("s1", "proj", "building", vec!["exit code 127"])];
    let refs: Vec<&IndexEntry> = entries.iter().collect();
    let path = write_digest(&dir, ProfileScope::Work, &refs, &[], now).unwrap();
    assert_eq!(
        path.file_name().unwrap().to_str().unwrap(),
        "digest-2026-W28.md"
    );
}

#[test]
fn digest_content_has_counts_and_facts() {
    let dir = tmp_dir("digest_content");
    let now = Utc.with_ymd_and_hms(2026, 7, 6, 12, 0, 0).unwrap();
    let entries = [
        entry("s1", "proj-a", "building", vec!["exit code 127"]),
        entry("s2", "proj-a", "debugging", vec!["exit code 127"]),
        entry("s3", "proj-b", "building", vec![]),
    ];
    let refs: Vec<&IndexEntry> = entries.iter().collect();
    let facts = vec![ProfileFact {
        section: ProfileSection::Timeline,
        fact: "Started HalluScribe.".to_string(),
        evidence: vec!["s1".to_string()],
        date: "2026-06-01".to_string(),
    }];
    let path = write_digest(&dir, ProfileScope::Work, &refs, &facts, now).unwrap();
    let content = fs::read_to_string(&path).unwrap();
    assert!(content.contains("3 sessions distilled this refresh."));
    assert!(content.contains("proj-a: 2"));
    assert!(content.contains("proj-b: 1"));
    assert!(content.contains("building: 2"));
    assert!(content.contains("debugging: 1"));
    assert!(content.contains("exit code 127: 2"));
    assert!(content.contains("Started HalluScribe."));
}

