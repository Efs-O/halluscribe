#[test]
fn scopes_have_independent_directories() {
    let dir = tmp_dir("scope_isolation");
    let meta = ProfileMeta {
        generated_at: "2026-07-04T00:00:00+00:00".to_string(),
        ..Default::default()
    };
    let mut work_sections = ProfileSections::default();
    work_sections.set(ProfileSection::Identity, "Work identity.".to_string());
    let mut personal_sections = ProfileSections::default();
    personal_sections.set(ProfileSection::Identity, "Personal identity.".to_string());
    personal_sections.set(
        ProfileSection::PersonalContext,
        "Enjoys hiking.".to_string(),
    );

    write_profile(&dir, ProfileScope::Work, &work_sections, &meta).unwrap();
    write_profile(&dir, ProfileScope::Personal, &personal_sections, &meta).unwrap();

    let work_md = read_profile_md(&dir, ProfileScope::Work).unwrap();
    let personal_md = read_profile_md(&dir, ProfileScope::Personal).unwrap();
    assert!(work_md.contains("Work identity."));
    assert!(!work_md.contains("Interests & Life Context"));
    assert!(personal_md.contains("Personal identity."));
    assert!(personal_md.contains("Interests & Life Context"));
    assert!(personal_md.contains("Enjoys hiking."));
    assert!(dir.join("profile").join("work").join("profile.md").exists());
    assert!(dir
        .join("profile")
        .join("personal")
        .join("profile.md")
        .exists());
}

#[test]
fn migrate_legacy_profile_layout_moves_files_into_work_dir() {
    let dir = tmp_dir("migration");
    let profile = dir.join("profile");
    fs::create_dir_all(&profile).unwrap();
    fs::write(profile.join("profile.md"), "# legacy profile").unwrap();
    fs::write(profile.join("profile_meta.json"), "{}").unwrap();
    fs::write(profile.join("digest-2026-W27.md"), "legacy digest").unwrap();

    // Any scoped read triggers the migration.
    let content = read_profile_md(&dir, ProfileScope::Work).unwrap();
    assert_eq!(content, "# legacy profile");

    let work = profile.join("work");
    assert!(work.join("profile.md").exists());
    assert!(work.join("profile_meta.json").exists());
    assert!(work.join("digest-2026-W27.md").exists());
    // Legacy top-level files are gone (moved, not copied).
    assert!(!profile.join("profile.md").exists());
    assert!(!profile.join("digest-2026-W27.md").exists());
}

#[test]
fn migrate_legacy_profile_layout_is_idempotent_and_missing_file_safe() {
    let dir = tmp_dir("migration_idempotent");
    let profile = dir.join("profile");
    fs::create_dir_all(&profile).unwrap();
    // Only profile.md exists (no meta, no digests) — must not panic.
    fs::write(profile.join("profile.md"), "# legacy profile").unwrap();

    migrate_legacy_profile_layout(&dir);
    assert!(profile.join("work").join("profile.md").exists());

    // Running again after work/profile.md already exists is a no-op that
    // must not error or clobber anything.
    fs::write(
        profile.join("work").join("profile.md"),
        "# already migrated",
    )
    .unwrap();
    migrate_legacy_profile_layout(&dir);
    assert_eq!(
        fs::read_to_string(profile.join("work").join("profile.md")).unwrap(),
        "# already migrated"
    );
}

#[test]
fn migrate_legacy_profile_layout_noop_when_no_legacy_file() {
    let dir = tmp_dir("migration_noop");
    // No profile dir at all — must not panic or create anything.
    migrate_legacy_profile_layout(&dir);
    assert!(!dir.join("profile").exists());
}

