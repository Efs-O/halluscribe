fn tmp_dir(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("halluscribe_profile_writer_{name}"));
    let _ = fs::remove_dir_all(&d);
    d
}

fn entry(id: &str, project: &str, session_type: &str, tags: Vec<&str>) -> IndexEntry {
    IndexEntry {
        id: id.to_string(),
        project: project.to_string(),
        date: "2026-06-01".to_string(),
        title: format!("Session {id}"),
        tool: "Claude Code".to_string(),
        fill_pct: 90.0,
        session_timestamp: "2026-06-01T00:00:00+00:00".to_string(),
        updated_at: String::new(),
        session_type: session_type.to_string(),
        error_tags: tags.into_iter().map(str::to_string).collect(),
        topic_tags: Vec::new(),
        archive_path: format!("sessions/{project}/{id}.md"),
        source_jsonl: String::new(),
        source_size_bytes: 0,
        provider: "claude_code".to_string(),
        fill_estimated: false,
        transcript_hash: String::new(),
        secret_flags: Vec::new(),
    }
}

